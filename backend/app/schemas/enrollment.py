"""
CyberGuard AI — Enrollment Token Schemas
============================================================================

Request/response DTOs for the ``source_enrollments`` table.

An enrollment token is the handoff point between "user wants to add a
device" and "collector has a credential". It is the only moment a
plaintext secret (the token itself) crosses from backend to collector.

Design rules
------------
1. **The plaintext token is shown exactly once.**
   ``EnrollmentTokenIssued`` is the only schema that carries it. Once
   issued, the client must capture it — it cannot be retrieved again.

2. **The token is bound to a specific source.**
   ``source_id`` is required at creation. A token enrolls exactly one
   source, no exceptions.

3. **TTL is enforced server-side.**
   Clients can request a ``ttl_minutes`` value; the service clamps it
   to ``[1, 60]``. Default is 15.

4. **The client cannot set ``token_hash``.**
   The service computes it. The client never sees the plaintext in the
   Create body — the service generates it via ``generate_secure_token``.

5. **Redemption schema is separate from creation.**
   ``EnrollmentRedemptionRequest`` is what the collector sends. It
   contains the plaintext token + collector metadata. It never carries
   the source_id — the source_id is resolved by looking up the token.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from pydantic import Field, field_validator

from app.schemas.common import (
    CyberGuardBaseSchema,
    ORMModel,
    TimestampedModel,
)


# ─── Constants ─────────────────────────────────────────────────────────────
_DEFAULT_TTL_MINUTES = 15
_MIN_TTL_MINUTES = 1
_MAX_TTL_MINUTES = 60

_HOSTNAME_MAX = 255
_IP_MAX = 45
_OS_VERSION_MAX = 64
_AGENT_VERSION_MAX = 32
_REASON_MAX = 500


# ============================================================================
# ISSUE (create)
# ============================================================================

class EnrollmentTokenCreate(CyberGuardBaseSchema):
    """
    Request body for ``POST /sources/{source_id}/enrollment``.

    The service generates the plaintext token, stores its bcrypt hash,
    and returns it in ``EnrollmentTokenIssued``. The client does not see
    ``token_hash`` — it's a server-managed field.
    """

    ttl_minutes: int = Field(
        default=_DEFAULT_TTL_MINUTES,
        ge=_MIN_TTL_MINUTES,
        le=_MAX_TTL_MINUTES,
        description=(
            f"Token lifetime in minutes ({_MIN_TTL_MINUTES}–{_MAX_TTL_MINUTES}). "
            "Default 15. Short windows are recommended — the token is a "
            "one-shot secret."
        ),
    )


class EnrollmentTokenIssued(CyberGuardBaseSchema):
    """
    Response when an enrollment token is created.

    **The only place the plaintext token appears in any API response.**
    The client must display it to the user (usually as a copyable
    string or QR code) immediately — it cannot be retrieved later.
    """

    enrollment_id: uuid.UUID
    source_id: uuid.UUID
    plaintext_token: str = Field(
        ...,
        description=(
            "The full enrollment token. Shown ONCE. Display it in the "
            "device-connection wizard; do not store it server-side or "
            "in client logs."
        ),
    )
    token_prefix: str = Field(
        ...,
        description="First 12 chars, for future log identification.",
    )
    expires_at: datetime = Field(
        ...,
        description="When this token ceases to be redeemable.",
    )
    seconds_until_expiry: int = Field(
        ...,
        description="Convenience: seconds from now until expires_at.",
    )


# ============================================================================
# REDEEM (collector → backend)
# ============================================================================

class EnrollmentRedemptionRequest(CyberGuardBaseSchema):
    """
    Request body for ``POST /collector/enroll``.

    Sent by a collector when it wants to exchange an enrollment token
    for a long-lived credential. The collector also reports device
    identity here — the backend records it on the resulting
    ``CollectorCredential`` row.
    """

    token: str = Field(
        ...,
        min_length=20,
        max_length=200,
        description="The plaintext enrollment token from the wizard.",
    )

    collector_id: uuid.UUID = Field(
        ...,
        description=(
            "Self-assigned UUID generated by the collector on first install. "
            "Persisted to disk on the device. Stable across token rotations."
        ),
    )

    hostname: str | None = Field(
        default=None,
        max_length=_HOSTNAME_MAX,
        description="Hostname reported by the collector.",
    )

    os_version: str | None = Field(
        default=None,
        max_length=_OS_VERSION_MAX,
        description="OS version string.",
    )

    agent_version: str | None = Field(
        default=None,
        max_length=_AGENT_VERSION_MAX,
        description="Collector version string.",
    )

    hardware_fingerprint: str | None = Field(
        default=None,
        max_length=80,
        description=(
            "Stable hash of physical device: 'sha256:<64 hex>'. Used by "
            "anti-spoofing to detect device-level anomalies across reinstalls."
        ),
    )

    @field_validator("token")
    @classmethod
    def _validate_token(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("token must not be empty")
        return stripped

    @field_validator("hardware_fingerprint")
    @classmethod
    def _validate_fingerprint(cls, v: str | None) -> str | None:
        if v is None:
            return None
        stripped = v.strip().lower()
        if not stripped:
            return None
        import re
        if not re.match(r"^sha256:[a-f0-9]{64}$", stripped):
            raise ValueError(
                "hardware_fingerprint must match 'sha256:<64 lowercase hex>'"
            )
        return stripped


class EnrollmentRedemptionResponse(CyberGuardBaseSchema):
    """
    Response to a successful enrollment.

    Contains the **plaintext credential** — the only time the collector
    will ever see it. The collector stores it in DPAPI (Windows) or
    secure storage (Linux), and uses it for all subsequent requests.
    """

    source_id: uuid.UUID
    collector_credential_id: uuid.UUID
    plaintext_credential: str = Field(
        ...,
        description=(
            "The full collector credential (e.g. 'cgc_<random>'). Shown "
            "ONCE at enrollment. The collector must persist it securely "
            "immediately — it cannot be retrieved again."
        ),
    )
    credential_prefix: str = Field(
        ...,
        description="First 12 chars, for future log identification.",
    )
    expires_at: datetime | None = Field(
        default=None,
        description="Optional credential expiry (rotation cadence is service-enforced).",
    )
    heartbeat_interval_seconds: int = Field(
        ...,
        description="How often the collector should send a heartbeat.",
    )
    api_base_url: str = Field(
        ...,
        description="Base URL for the collector's subsequent API calls.",
    )


# ============================================================================
# READ
# ============================================================================

class EnrollmentTokenRead(TimestampedModel):
    """
    Full enrollment token view. Never includes the plaintext or hash.

    Returned by list/get endpoints for admin visibility into pending
    enrollments.
    """

    id: uuid.UUID
    source_id: uuid.UUID
    created_by_id: uuid.UUID | None = None

    token_prefix: str
    expires_at: datetime

    redeemed_at: datetime | None = None
    redeemed_by_id: uuid.UUID | None = None
    redeemed_ip: str | None = None
    collector_version: str | None = None

    revoked_at: datetime | None = None
    revocation_reason: str | None = None

    # Computed
    is_redeemed: bool = Field(..., description="True if the token has been used.")
    is_revoked: bool = Field(..., description="True if explicitly revoked.")
    is_expired: bool = Field(..., description="True if past expires_at.")
    is_redeemable: bool = Field(
        ...,
        description="True if the token can still be redeemed (not used/revoked/expired).",
    )
    display_status: str = Field(
        ...,
        description="One of: 'pending', 'redeemed', 'revoked', 'expired'.",
    )


