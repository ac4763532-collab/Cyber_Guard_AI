class EnrollmentTokenRevokeRequest(CyberGuardBaseSchema):
    """Request body for revoking a pending enrollment token."""

    reason: str = Field(
        ...,
        min_length=1,
        max_length=_REASON_MAX,
        description="Why the token is being revoked. Recorded in audit log.",
    )


