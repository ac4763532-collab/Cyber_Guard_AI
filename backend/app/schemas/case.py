class CaseAccessGrantCreate(CyberGuardBaseSchema):
    """
    Request body for ``POST /cases/{id}/access-grants``.

    This is the schema-level enforcement of the platform's core
    security rule: org admins and external users get **no implicit
    access to a case** — every non-assigned viewer needs an explicit,
    purpose-recorded, expirable, revocable grant.

    ``purpose`` is required. Grants without a recorded reason are
    rejected at schema validation time — before the service, before
    the DB. This is the audit trail.
    """

    grantee_user_id: uuid.UUID = Field(
        ...,
        description="User receiving the grant.",
    )
    scope: AccessGrantScope = Field(
        default=AccessGrantScope.CASE_READ,
        description=(
            "case_read | evidence_read | conversation_read | full_case. "
            "Least privilege by default — evidence and conversation "
            "scopes must be explicitly requested."
        ),
    )
    purpose: str = Field(
        ...,
        min_length=1,
        max_length=_PURPOSE_MAX,
        description=(
            "Why access is being granted. Required. E.g. "
            "'Phishing investigation — ₹499 engagement' or "
            "'Compliance audit 2026-Q1'."
        ),
    )
    expires_at: datetime | None = Field(
        default=None,
        description=(
            "Optional time limit. Recommended for marketplace "
            "engagements. After expiry, the grant is no longer "
            "effective (is_active=False) without any cleanup job."
        ),
    )
    notes: str | None = Field(default=None, max_length=_NOTE_MAX)

    @field_validator("purpose")
    @classmethod
    def _clean_purpose(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("purpose must not be empty")
        return stripped

    @field_validator("expires_at")
    @classmethod
    def _validate_expiry(cls, v: datetime | None) -> datetime | None:
        if v is None:
            return None
        from datetime import datetime as dt, timezone
        if v.tzinfo is None:
            v = v.replace(tzinfo=timezone.utc)
        if v <= dt.now(timezone.utc):
            raise ValueError(
                "expires_at must be in the future. "
                "Grants with past expiry are meaningless."
            )
        return v


