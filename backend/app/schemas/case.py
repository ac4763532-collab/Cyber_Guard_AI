# ─── Constants ─────────────────────────────────────────────────────────────
_TITLE_MAX = 255
_DESCRIPTION_MAX = 10_000
_SUMMARY_MAX = 10_000
_RESOLUTION_MAX = 10_000
_NOTE_MAX = 5000
_PURPOSE_MAX = 500
_REASON_MAX = 500
_TAGS_MAX = 30
_CONTEXT_MAX_BYTES = 64 * 1024

_ASSIGNMENT_ROLES = frozenset({"primary", "backup", "reviewer"})
_NOTE_TYPES = frozenset({
    "observation", "action", "communication", "finding",
})


