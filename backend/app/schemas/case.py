# ============================================================================

class CaseCreate(CyberGuardBaseSchema):
    """
    Request body for ``POST /cases``.

    Creates a new case. ``case_number`` is generated by the service.

    Two paths:
      - With ``incident_id``: standard incident-driven case.
      - Without ``incident_id``: proactive work (drill, audit,
        marketplace engagement). Service flags ``is_billable`` if
        ``linked_engagement_id`` is set.
    """

    title: str = Field(..., min_length=1, max_length=_TITLE_MAX)
    description: str | None = Field(default=None, max_length=_DESCRIPTION_MAX)

    incident_id: uuid.UUID | None = Field(
        default=None,
        description=(
            "Incident this case investigates. NULL for proactive work, "
            "compliance audits, or drills."
        ),
    )

    priority: CasePriority = Field(default=CasePriority.MEDIUM)
    severity: EventSeverity = Field(default=EventSeverity.MEDIUM)
    category: FindingCategory = Field(default=FindingCategory.OTHER)

    assigned_to_id: uuid.UUID | None = Field(
        default=None,
        description="Initial primary analyst (must have a verified analyst profile).",
    )

    tags: list[str] = Field(default_factory=list, max_length=_TAGS_MAX)
    context: dict[str, Any] = Field(default_factory=dict)

    is_billable: bool = Field(
        default=False,
        description="True if work on this case is billable (marketplace flow).",
    )
    linked_engagement_id: uuid.UUID | None = Field(
        default=None,
        description="FK to the marketplace purchase that funded this case.",
    )

    @field_validator("title")
    @classmethod
    def _clean_title(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("title must not be empty")
        return stripped

    @field_validator("context")
    @classmethod
    def _validate_context_size(cls, v: dict[str, Any]) -> dict[str, Any]:
        try:
            size = len(json.dumps(v, default=str).encode("utf-8"))
        except (TypeError, ValueError) as exc:
            raise ValueError(f"context is not JSON-serializable: {exc}")
        if size > _CONTEXT_MAX_BYTES:
            raise ValueError(
                f"context exceeds {_CONTEXT_MAX_BYTES} bytes (got {size})"
            )
        return v


