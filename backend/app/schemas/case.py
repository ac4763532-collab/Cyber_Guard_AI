"""
CyberGuard AI — Security Case Schemas
============================================================================

Request/response DTOs for:

    - ``security_cases``         — the analyst work assignment wrapper
    - ``case_assignments``       — assignment history (primary / backup / reviewer)
    - ``case_access_grants``     — explicit scoped access grants

These three tables are the platform's access-control system for cases.
The schemas here implement the security rule from the project handover:

    "An organization administrator should not automatically gain access
     to all client evidence. Sensitive access must be explicitly granted
     and audited."

Design rules
------------
1. **Case creation requires incident_id OR is flagged proactive.**
   ``CaseCreate.incident_id`` is optional — proactive cases (drills,
   audits) don't need an incident. But the service layer distinguishes
   the two paths for reporting/audit clarity.

2. **``case_number`` is server-generated.**
   Format ``CG-YYYY-NNNNNN``. Clients never supply it.
   Generated by ``case_service``.

3. **Assignment and access grant are separate flows.**
   - ``CaseAssignmentCreate`` — "this analyst does the work"
   - ``CaseAccessGrantCreate`` — "this user can see specific parts"

   A user must have BOTH (or be an admin of the workspace) to work
   on a case. The access grant is the schema-level enforcement that
   admin role ≠ evidence access.

4. **Access grants have mandatory ``purpose`` field.**
   Every grant records why it was issued. Enforced at schema level.
   This is the audit trail that answers "why did Rahul see Priya's
   evidence on 2026-03-14?"

5. **Grants are time-limited and revocable.**
   ``expires_at`` is optional but recommended. ``revoked_at`` is
   terminal — a revoked grant cannot be reactivated. To restore
   access, create a new grant (which appears as a new audit event).

6. **Four access scopes.**
   ``case_read`` | ``evidence_read`` | ``conversation_read`` |
   ``full_case``. Least privilege by default: ``case_read``.

7. **Investigation notes are append-only JSONB.**
   ``CaseInvestigationNoteCreate`` adds one note. There is no
   ``CaseInvestigationNoteUpdate`` — notes are immutable once written.

8. **Case status transitions are validated.**
   ``CaseStatusUpdate`` accepts the target status; the service
   enforces the allowed transitions (see ``_ALLOWED_CASE_TRANSITIONS``
   in ``case.py`` model).
"""

