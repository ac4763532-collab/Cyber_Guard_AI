class ReportingAgent(BaseAgent):
    """
    Schedules and orchestrates report generation for workspaces.

    See package docstring for the invocation model.
    """

    name = "reporting"

    def __init__(self, config: dict[str, Any] | None = None) -> None:
        super().__init__(config)
        self._max_rows = int(self._config.get("max_rows", 10000))
        self._pdf_page_limit = int(self._config.get("pdf_page_limit", 100))

    # ── Standard agent interface — on-demand single report ─────────────

    def process(self, context: AgentContext) -> AgentResult:
        """
        On-demand single report generation.

        Reads the target from ``correlation_state``:

            correlation_state["report_request"] = {
                "workspace_id": str,
                "report_type": str,          # "daily", "incident", ...
                "report_format": str,        # "pdf", "csv", ...
                "title": str,
                "scope_type": str,           # "workspace", "incident", "case"
                "scope_id": str | None,
                "sections": [str],
                "parameters": {str: any},
                "period_start_at": str | None,
                "period_end_at": str | None,
                "requested_by_id": str | None,
            }

        Used by the API endpoint ``POST /api/v1/reports`` when the
        caller wants synchronous generation (rare) OR by an admin
        endpoint for forcing a specific report.

        For the common case (async request + background worker), the
        API endpoint calls ``report_service.request_report`` directly
        and returns immediately. This agent method is for the sync path.
        """
        request_data = (context.correlation_state or {}).get("report_request")
        if not request_data:
            return AgentResult(
                findings=[],
                errors=[
                    {
                        "stage": "extract",
                        "code": "REPORTING_NO_REQUEST",
                        "message": (
                            "ReportingAgent.process() requires "
                            "correlation_state['report_request']."
                        ),
                        "traceback": None,
                    }
                ],
                metadata={"mode": "on_demand"},
            )

        try:
            report = self._create_and_generate(context.db, request_data)
        except Exception as exc:  # noqa: BLE001
            self._logger.exception(
                "On-demand report generation failed",
                extra={"error": str(exc)[:300]},
            )
            return AgentResult(
                findings=[],
                errors=[
                    self._wrap_error(stage="generate", exception=exc),
                ],
                metadata={"mode": "on_demand"},
            )

        return AgentResult(
            findings=[],
            errors=[],
            metadata={
                "mode": "on_demand",
                "report_id": str(report.id),
                "generation_status": report.generation_status.value,
                "report_format": report.report_format,
            },
        )

    def _create_and_generate(
        self,
        db,
        request_data: dict[str, Any],
    ) -> SecurityReport:
        """Create the report row, then generate synchronously."""
        # Build ReportCreate from the request
        payload = ReportCreate(
            report_type=ReportType(request_data["report_type"]),
            report_format=request_data.get("report_format", "pdf"),
            title=request_data["title"],
            summary=request_data.get("summary"),
            scope_type=request_data.get("scope_type", "workspace"),
            scope_id=(
                uuid.UUID(request_data["scope_id"])
                if request_data.get("scope_id") else None
            ),
            period_start_at=_parse_dt(request_data.get("period_start_at")),
            period_end_at=_parse_dt(request_data.get("period_end_at")),
            sections=request_data.get("sections") or [],
            parameters=request_data.get("parameters") or {},
        )

        # Request: creates the QUEUED row
        report = report_service.request_report(
            db,
            actor_id=(
                uuid.UUID(request_data["requested_by_id"])
                if request_data.get("requested_by_id") else None
            ),
            payload=payload,
        )

        # Generate synchronously (blocks until the file is on disk)
        report_service.generate_report(db, report=report)
        return report

    # ── Scheduled sweep ────────────────────────────────────────────────

    def run_scheduled_reports(
        self,
        db,
        frequency: Frequency,
    ) -> dict[str, int]:
        """
        Generate one report per active workspace for the given frequency.

        Idempotent — skipping workspaces that already have a report of
        this type for the current period.

        Returns counters:
            workspaces_scanned   int
            reports_created      int
            reports_failed       int
            skipped_existing     int
        """
        if frequency not in _FREQUENCY_TO_REPORT_TYPE:
            raise AgentError(
                message=f"Unknown frequency: {frequency!r}",
                code="REPORTING_FREQUENCY_INVALID",
            )

        report_type = _FREQUENCY_TO_REPORT_TYPE[frequency]
        period_start, period_end = _compute_period(frequency)

        counts = {
            "workspaces_scanned": 0,
            "reports_created": 0,
            "reports_failed": 0,
            "skipped_existing": 0,
        }

        # Find active workspaces (personal + organization; skip archived)
        workspaces = list(db.execute(
            select(Workspace).where(
                Workspace.deleted_at.is_(None),
                Workspace.workspace_type.in_((
                    WorkspaceType.PERSONAL,
                    WorkspaceType.ORGANIZATION,
                )),
            ).limit(_MAX_WORKSPACES_PER_RUN)
        ).scalars().all())

        counts["workspaces_scanned"] = len(workspaces)

        for workspace in workspaces:
            # Check whether a report already exists for this period
            if self._report_exists_for_period(
                db,
                workspace_id=workspace.id,
                report_type=report_type,
                period_start=period_start,
            ):
                counts["skipped_existing"] += 1
                continue

            # Generate each scheduled format
            for fmt in _SCHEDULED_FORMATS:
                try:
                    self._generate_scheduled_report(
                        db,
                        workspace=workspace,
                        report_type=report_type,
                        frequency=frequency,
                        report_format=fmt,
                        period_start=period_start,
                        period_end=period_end,
                    )
                    counts["reports_created"] += 1
                except Exception as exc:  # noqa: BLE001
                    counts["reports_failed"] += 1
                    self._logger.exception(
                        "Scheduled report failed",
                        extra={
                            "workspace_id": str(workspace.id),
                            "frequency": frequency,
                            "format": fmt,
                            "error": str(exc)[:300],
                        },
                    )

        if counts["reports_created"] > 0 or counts["reports_failed"] > 0:
            self._logger.info(
                "Scheduled reports complete",
                extra={
                    "frequency": frequency,
                    "period_start": period_start.isoformat(),
                    "period_end": period_end.isoformat(),
                    **counts,
                },
            )

        return counts

    def _report_exists_for_period(
        self,
        db,
        *,
        workspace_id: uuid.UUID,
        report_type: ReportType,
        period_start: datetime,
    ) -> bool:
        """
        True if a report of this type already exists for this workspace
        covering the current period.

        Any format counts — we don't generate the same report type
        twice for the same period.
        """
        existing = db.execute(
            select(SecurityReport.id).where(
                SecurityReport.workspace_id == workspace_id,
                SecurityReport.report_type == report_type,
                SecurityReport.period_start_at == period_start,
                SecurityReport.generation_status.in_((
                    ReportStatus.QUEUED,
                    ReportStatus.GENERATING,
                    ReportStatus.READY,
                )),
                SecurityReport.deleted_at.is_(None),
            ).limit(1)
        ).scalar_one_or_none()
        return existing is not None

    def _generate_scheduled_report(
        self,
        db,
        *,
        workspace: Workspace,
        report_type: ReportType,
        frequency: Frequency,
        report_format: str,
        period_start: datetime,
        period_end: datetime,
    ) -> SecurityReport:
        """Create and generate one report for one workspace."""
        # Title is human-readable
        frequency_label = frequency.capitalize()
        workspace_name = workspace.name or workspace.slug
        title = f"{frequency_label} Security Report — {workspace_name}"

        payload = ReportCreate(
            report_type=report_type,
            report_format=report_format,
            title=title[:255],
            summary=None,  # auto-generated by report_service
            scope_type="workspace",
            scope_id=workspace.id,
            period_start_at=period_start,
            period_end_at=period_end,
            sections=[],   # use defaults for the report type
            parameters={
                "generated_by": "reporting_agent",
                "frequency": frequency,
                "scheduled": True,
                "period_start": period_start.isoformat(),
                "period_end": period_end.isoformat(),
            },
            is_scheduled=True,
        )

        report = report_service.request_report(
            db,
            actor_id=None,   # system-generated
            payload=payload,
        )

        report_service.generate_report(db, report=report)
        return report


