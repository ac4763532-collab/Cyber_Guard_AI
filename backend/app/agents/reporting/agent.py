def _parse_dt(value: Any) -> datetime | None:
    """Parse an ISO-8601 timestamp (or return None)."""
    if not value:
        return None
    if isinstance(value, datetime):
        return value
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except (ValueError, TypeError):
        return None


