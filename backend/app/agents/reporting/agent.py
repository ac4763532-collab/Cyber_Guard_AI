"""
CyberGuard AI — Reporting Agent
============================================================================

Generates scheduled and on-demand security reports via
``report_service``.

Two invocation modes
--------------------
    process(context) — single-report generation. Called from API
                       endpoints when a user manually requests a
                       report or when the runtime wants to force
                       one specific report.

    run_scheduled_reports(db, frequency) — batch. Called from a
                       periodic task (cron, runtime thread, or
                       ``main.py`` lifespan hook). Generates one
                       report per active workspace for the given
                       frequency, skipping workspaces that already
                       have a report for the current period.

Idempotency
-----------
``run_scheduled_reports`` is idempotent — running it 3 times in one
day for frequency="daily" produces **1 report per workspace**, not 3.
The check is:

    "does a report of this type exist in this workspace, with
     period_start_at within the current day, and generation_status
     in (QUEUED, GENERATING, READY)?"

If yes → skip. If no → create.

Period computation
------------------
    daily     — period_start_at = today at 00:00 UTC
                period_end_at   = tomorrow at 00:00 UTC
    weekly    — period_start_at = Monday 00:00 UTC of this week
                period_end_at   = next Monday 00:00 UTC
    monthly   — period_start_at = 1st of this month at 00:00 UTC
                period_end_at   = 1st of next month at 00:00 UTC

Reports use ``report_service.generate_report`` which is synchronous
(blocks until the file is written). For a mid-sized workspace, this is
2–5 seconds. For a large workspace with many events, 10–30 seconds.
The scheduler should run with a generous timeout (60s per report).

Config (from settings via runtime)
----------------------------------
    report_max_rows: int           — passed to report_service (default 10000)
    report_pdf_page_limit: int     — passed to report_service (default 100)
"""

from __future__ import annotations

import uuid
from datetime import datetime, timedelta, timezone
from typing import Any, Literal

from sqlalchemy import and_, func, or_, select

from app.agents.base import AgentContext, AgentResult, BaseAgent
from app.core.exceptions import AgentError
from app.core.logging import get_logger
from app.models.enums import (
    ReportStatus,
    ReportType,
    WorkspaceType,
)
from app.models.report import SecurityReport
from app.models.workspace import Workspace
from app.schemas.report import ReportCreate
from app.services import report_service


logger = get_logger(__name__)


# ============================================================================
# CONSTANTS
# ============================================================================

Frequency = Literal["daily", "weekly", "monthly"]

_FREQUENCY_TO_REPORT_TYPE: dict[str, ReportType] = {
    "daily": ReportType.DAILY,
    "weekly": ReportType.WEEKLY,
    "monthly": ReportType.MONTHLY,
}

#: Cap on workspaces per scheduled run — prevents one runaway scheduler
#: run from holding the DB connection for minutes. If more workspaces
#: exist, the next tick picks up where this one left off (idempotent).
_MAX_WORKSPACES_PER_RUN = 200

#: Report formats generated by default. PDF is the primary format
#: (users read these); CSV is included for spreadsheet-friendly
#: variants. JSON/HTML are on-demand only.
_SCHEDULED_FORMATS: tuple[str, ...] = ("pdf", "csv")


# ============================================================================
# PERIOD HELPERS
# ============================================================================

def _compute_period(
    frequency: Frequency,
    now: datetime | None = None,
) -> tuple[datetime, datetime]:
    """
    Return ``(period_start_at, period_end_at)`` for the given frequency.

    All boundaries are UTC. Aligns to natural calendar boundaries:
    daily = midnight, weekly = Monday midnight, monthly = 1st midnight.
    """
    if now is None:
        now = datetime.now(timezone.utc)

    # Normalize to midnight today
    today_start = now.replace(hour=0, minute=0, second=0, microsecond=0)

    if frequency == "daily":
        start = today_start
        end = today_start + timedelta(days=1)

    elif frequency == "weekly":
        # Monday is 0; today's weekday() tells us how many days back
        # to go to reach Monday
        days_since_monday = today_start.weekday()
        start = today_start - timedelta(days=days_since_monday)
        end = start + timedelta(days=7)

    elif frequency == "monthly":
        start = today_start.replace(day=1)
        # Next month's 1st = (start + 32 days).replace(day=1)
        # (32 days always lands in the next month from the 1st)
        end = (start + timedelta(days=32)).replace(day=1)

    else:
        raise AgentError(
            message=f"Unknown frequency: {frequency!r}",
            code="REPORTING_FREQUENCY_INVALID",
        )

    return start, end


