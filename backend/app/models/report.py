    @validates("title")
    def _validate_title(self, _key: str, value: str) -> str:
        if not isinstance(value, str):
            raise ValidationError(
                message="title must be a string",
                code="REPORT_TITLE_INVALID_TYPE",
            )
        stripped = value.strip()
        if not stripped:
            raise ValidationError(
                message="title must not be empty",
                code="REPORT_TITLE_EMPTY",
            )
        if len(stripped) > _MAX_TITLE_LENGTH:
            raise ValidationError(
                message=f"title must not exceed {_MAX_TITLE_LENGTH} characters",
                code="REPORT_TITLE_TOO_LONG",
            )
        return stripped

    @validates("report_format")
    def _validate_format(self, _key: str, value: str) -> str:
        if not isinstance(value, str):
            raise ValidationError(
                message="report_format must be a string",
                code="REPORT_FORMAT_INVALID_TYPE",
            )
        normalized = value.strip().lower()
        if normalized not in _VALID_REPORT_FORMATS:
            raise ValidationError(
                message=f"report_format must be one of {sorted(_VALID_REPORT_FORMATS)}",
                code="REPORT_FORMAT_INVALID",
                details={
                    "received": value,
                    "allowed": sorted(_VALID_REPORT_FORMATS),
                },
            )
        return normalized

    @validates("scope_type")
    def _validate_scope_type(self, _key: str, value: str) -> str:
        if not isinstance(value, str):
            raise ValidationError(
                message="scope_type must be a string",
                code="REPORT_SCOPE_TYPE_INVALID_TYPE",
            )
        normalized = value.strip().lower()
        if normalized not in _VALID_SCOPE_TYPES:
            raise ValidationError(
                message=f"scope_type must be one of {sorted(_VALID_SCOPE_TYPES)}",
                code="REPORT_SCOPE_TYPE_INVALID",
                details={
                    "received": value,
                    "allowed": sorted(_VALID_SCOPE_TYPES),
                },
            )
        return normalized

    @validates("report_type")
    def _validate_report_type(
        self, _key: str, value: ReportType | str
    ) -> ReportType:
        if isinstance(value, ReportType):
            return value
        if isinstance(value, str):
            try:
                return ReportType(value)
            except ValueError as exc:
                raise ValidationError(
                    message=f"Invalid report_type {value!r}",
                    code="REPORT_TYPE_INVALID",
                    details={"allowed": list(ReportType.values())},
                ) from exc
        raise ValidationError(
            message="report_type must be a ReportType or string",
            code="REPORT_TYPE_INVALID_TYPE",
        )

    @validates("generation_status")
    def _validate_status(
        self, _key: str, value: ReportStatus | str
    ) -> ReportStatus:
        if isinstance(value, ReportStatus):
            return value
        if isinstance(value, str):
            try:
                return ReportStatus(value)
            except ValueError as exc:
                raise ValidationError(
                    message=f"Invalid generation_status {value!r}",
                    code="REPORT_STATUS_INVALID",
                    details={"allowed": list(ReportStatus.values())},
                ) from exc
        raise ValidationError(
            message="generation_status must be a ReportStatus or string",
            code="REPORT_STATUS_INVALID_TYPE",
        )

    @validates("content_hash")
    def _validate_hash(self, _key: str, value: str | None) -> str | None:
        if value is None:
            return None
        if not isinstance(value, str):
            raise ValidationError(
                message="content_hash must be a string or None",
                code="REPORT_HASH_INVALID_TYPE",
            )
        normalized = value.strip().lower()
        if not _SHA256_PATTERN.match(normalized):
            raise ValidationError(
                message="content_hash must be 64 lowercase hex characters",
                code="REPORT_HASH_INVALID_FORMAT",
            )
        return normalized

    @validates("sections")
    def _validate_sections(self, _key: str, value: list[str] | None) -> list[str]:
        if value is None:
            return []
        if not isinstance(value, list):
            raise ValidationError(
                message="sections must be a list of strings",
                code="REPORT_SECTIONS_INVALID_TYPE",
            )
        if len(value) > _MAX_SECTIONS:
            raise ValidationError(
                message=f"sections must not exceed {_MAX_SECTIONS} items",
                code="REPORT_SECTIONS_TOO_MANY",
            )
        cleaned: list[str] = []
        seen: set[str] = set()
        for item in value:
            if not isinstance(item, str):
                raise ValidationError(
                    message="each section must be a string",
                    code="REPORT_SECTION_INVALID_TYPE",
                )
            stripped = item.strip().lower()
            if not stripped or stripped in seen:
                continue
            if len(stripped) > 64:
                raise ValidationError(
                    message="each section must not exceed 64 characters",
                    code="REPORT_SECTION_TOO_LONG",
                )
            seen.add(stripped)
            cleaned.append(stripped)
        return cleaned

    @validates("shared_with")
    def _validate_shared_with(
        self, _key: str, value: list[dict[str, Any]] | None
    ) -> list[dict[str, Any]]:
        if value is None:
            return []
        if not isinstance(value, list):
            raise ValidationError(
                message="shared_with must be a list of objects",
                code="REPORT_SHARED_WITH_INVALID_TYPE",
            )
        if len(value) > _MAX_SHARED_WITH:
            raise ValidationError(
                message=f"shared_with must not exceed {_MAX_SHARED_WITH} entries",
                code="REPORT_SHARED_WITH_TOO_MANY",
            )
        cleaned: list[dict[str, Any]] = []
        seen: set[str] = set()
        for item in value:
            if not isinstance(item, dict):
                raise ValidationError(
                    message="each shared_with entry must be an object",
                    code="REPORT_SHARED_WITH_ITEM_INVALID_TYPE",
                )
            uid = item.get("user_id")
            if not uid:
                raise ValidationError(
                    message="each shared_with entry must have user_id",
                    code="REPORT_SHARED_WITH_ITEM_MISSING_USER",
                )
            uid_str = str(uid)
            if uid_str in seen:
                continue
            seen.add(uid_str)
            cleaned.append({
                "user_id": uid_str,
                "shared_at": item.get("shared_at"),
                "shared_by_id": item.get("shared_by_id"),
                "expires_at": item.get("expires_at"),
            })
        return cleaned

    # ====================================================================
    # CONSTRUCTION HELPER
    # ====================================================================

    @classmethod
    def build(
        cls,
        *,
        workspace_id: uuid.UUID,
        report_type: ReportType,
        title: str,
        report_format: str = "pdf",
        scope_type: str = "workspace",
        scope_id: uuid.UUID | None = None,
        requested_by_id: uuid.UUID | None = None,
        report_group_id: uuid.UUID | None = None,
        regenerated_from_id: uuid.UUID | None = None,
        summary: str | None = None,
        parameters: dict[str, Any] | None = None,
        sections: list[str] | None = None,
        period_start_at: datetime | None = None,
        period_end_at: datetime | None = None,
        is_scheduled: bool = False,
        schedule_id: uuid.UUID | None = None,
        expires_in_days: int | None = _DEFAULT_EXPIRY_DAYS,
        metadata: dict[str, Any] | None = None,
    ) -> "SecurityReport":
        """
        Construct a new report in the QUEUED state.

        The caller must separately queue the generation job. When
        generation completes, call ``finish_generation()`` or
        ``fail_generation()``.

        ``report_group_id`` — if not provided, the new report's own id is
        used as its group id. For a second format of the same logical
        report, pass the original's ``report_group_id``.
        """
        now = datetime.now(timezone.utc)
        expires = (
            now + timedelta(days=expires_in_days)
            if expires_in_days is not None
            else None
        )

        rpt = cls(
            workspace_id=workspace_id,
            report_group_id=report_group_id or uuid.uuid4(),
            regenerated_from_id=regenerated_from_id,
            requested_by_id=requested_by_id,
            report_type=report_type,
            report_format=report_format,
            title=title,
            summary=summary,
            scope_type=scope_type,
            scope_id=scope_id,
            period_start_at=period_start_at,
            period_end_at=period_end_at,
            sections=sections or [],
            parameters=parameters or {},
            generation_status=ReportStatus.QUEUED,
            is_scheduled=is_scheduled,
            schedule_id=schedule_id,
            expires_at=expires,
            metadata_json=metadata or {},
        )
        # If this is a "fresh" report, ensure report_group_id matches its id
        # — but we can't set it to self.id before flush, so the caller may
        # need to update it after flush if it wants that behavior. For
        # correctness, the caller can pass report_group_id explicitly.
        return rpt

    # ====================================================================
    # GENERATION LIFECYCLE
    # ====================================================================

    def start_generation(self) -> None:
        """
        Transition from QUEUED to GENERATING. Called by a worker that
        picks up the job.
        """
        if self.generation_status != ReportStatus.QUEUED:
            raise ValidationError(
                message=(
                    f"Cannot start generation from status "
                    f"{self.generation_status.value!r}"
                ),
                code="REPORT_GENERATION_NOT_QUEUED",
            )
        self.generation_status = ReportStatus.GENERATING
        self.generation_started_at = datetime.now(timezone.utc)

    def finish_generation(
        self,
        *,
        content_hash: str,
        file_size_bytes: int,
        summary: str | None = None,
        page_count: int | None = None,
    ) -> None:
        """
        Transition from GENERATING to READY. Called by the worker after
        successfully writing the file to disk.
        """
        if self.generation_status != ReportStatus.GENERATING:
            raise ValidationError(
                message=(
                    f"Cannot finish generation from status "
                    f"{self.generation_status.value!r}"
                ),
                code="REPORT_GENERATION_NOT_IN_PROGRESS",
            )
        if file_size_bytes <= 0 or file_size_bytes > _MAX_FILE_SIZE_BYTES:
            raise ValidationError(
                message=(
                    f"file_size_bytes must be between 1 and "
                    f"{_MAX_FILE_SIZE_BYTES}"
                ),
                code="REPORT_FILE_SIZE_OUT_OF_RANGE",
                details={"received": file_size_bytes},
            )
        if page_count is not None and (
            page_count < 0 or page_count > _MAX_PAGE_COUNT
        ):
            raise ValidationError(
                message=f"page_count must be between 0 and {_MAX_PAGE_COUNT}",
                code="REPORT_PAGE_COUNT_OUT_OF_RANGE",
            )

        now = datetime.now(timezone.utc)
        self.generation_status = ReportStatus.READY
        self.generation_completed_at = now
        self.content_hash = content_hash
        self.file_size_bytes = file_size_bytes
        if summary is not None:
            self.summary = summary
        if page_count is not None:
            self.page_count = page_count
        if self.generation_started_at is not None:
            started = self.generation_started_at
            if started.tzinfo is None:
                started = started.replace(tzinfo=timezone.utc)
            self.generation_duration_seconds = int((now - started).total_seconds())

    def fail_generation(
        self,
        *,
        error_code: str,
        error_message: str | None = None,
    ) -> None:
        """Transition from GENERATING (or QUEUED) to FAILED."""
        if self.generation_status not in (ReportStatus.QUEUED, ReportStatus.GENERATING):
            raise ValidationError(
                message=(
                    f"Cannot fail generation from status "
                    f"{self.generation_status.value!r}"
                ),
                code="REPORT_GENERATION_NOT_IN_PROGRESS",
            )
        if not error_code or not isinstance(error_code, str):
            raise ValidationError(
                message="error_code must be a non-empty string",
                code="REPORT_ERROR_CODE_REQUIRED",
            )
        now = datetime.now(timezone.utc)
        self.generation_status = ReportStatus.FAILED
        self.generation_completed_at = now
        self.error_code = error_code.strip().upper()
        if error_message:
            self.error_message = error_message.strip()
        if self.generation_started_at is not None:
            started = self.generation_started_at
            if started.tzinfo is None:
                started = started.replace(tzinfo=timezone.utc)
            self.generation_duration_seconds = int((now - started).total_seconds())

    # ====================================================================
    # FILE INTEGRITY
    # ====================================================================

    def record_integrity_check(self, *, passed: bool) -> None:
        """Record the outcome of an integrity check on the report file."""
        self.last_integrity_check_at = datetime.now(timezone.utc)
        if not passed:
            self.integrity_verified = False

    # ====================================================================
    # DOWNLOAD TRACKING
    # ====================================================================

    def record_download(self) -> None:
        """Increment download count and update the timestamp."""
        self.download_count += 1
        self.last_downloaded_at = datetime.now(timezone.utc)

    # ====================================================================
    # SHARING
    # ====================================================================

    def share_with(
        self,
        *,
        user_id: uuid.UUID,
        shared_by_id: uuid.UUID,
        expires_at: datetime | None = None,
    ) -> None:
        """
        Add a user to the shared_with list. Idempotent — re-sharing with
        the same user is a no-op (existing entry is left untouched).
        """
        uid = str(user_id)
        existing = list(self.shared_with or [])
        for entry in existing:
            if entry.get("user_id") == uid:
                return
        if len(existing) >= _MAX_SHARED_WITH:
            raise ValidationError(
                message=f"shared_with has reached the maximum of {_MAX_SHARED_WITH}",
                code="REPORT_SHARED_WITH_LIMIT",
            )
        existing.append({
            "user_id": uid,
            "shared_at": datetime.now(timezone.utc).isoformat(),
            "shared_by_id": str(shared_by_id),
            "expires_at": expires_at.isoformat() if expires_at else None,
        })
        self.shared_with = existing

    def unshare_with(self, *, user_id: uuid.UUID) -> None:
        """Remove a user from the shared_with list. Idempotent."""
        uid = str(user_id)
        existing = [
            e for e in (self.shared_with or [])
            if e.get("user_id") != uid
        ]
        self.shared_with = existing

    def is_shared_with(self, *, user_id: uuid.UUID) -> bool:
        """True if the given user has an active share of this report."""
        uid = str(user_id)
        for entry in self.shared_with or []:
            if entry.get("user_id") != uid:
                continue
            exp = entry.get("expires_at")
            if exp is None:
                return True
            try:
                exp_dt = datetime.fromisoformat(exp)
                if exp_dt.tzinfo is None:
                    exp_dt = exp_dt.replace(tzinfo=timezone.utc)
                return exp_dt > datetime.now(timezone.utc)
            except (ValueError, TypeError):
                return False
        return False

    # ====================================================================
    # STORAGE
    # ====================================================================

    def get_storage_path(self) -> Path:
        """
        Compute the on-disk path for the generated report file.

        Layout: {REPORT_OUTPUT_DIR}/{workspace_id}/{report_id}.{format}
        """
        base = Path(settings.REPORT_OUTPUT_DIR).resolve()
        return base / str(self.workspace_id) / f"{self.id}.{self.report_format}"

    # ====================================================================
    # STATE PROPERTIES
    # ====================================================================

    @property
    def is_ready(self) -> bool:
        """True if the report file has been generated."""
        return self.generation_status == ReportStatus.READY

    @property
    def is_failed(self) -> bool:
        """True if generation failed."""
        return self.generation_status == ReportStatus.FAILED

    @property
    def is_pending(self) -> bool:
        """True if the report is queued or generating."""
        return self.generation_status in (
            ReportStatus.QUEUED,
            ReportStatus.GENERATING,
        )

    @property
    def is_expired(self) -> bool:
        """True if the report's expires_at has passed."""
        if self.expires_at is None:
            return False
        exp = self.expires_at
        if exp.tzinfo is None:
            exp = exp.replace(tzinfo=timezone.utc)
        return exp <= datetime.now(timezone.utc)

    @property
    def is_under_legal_hold(self) -> bool:
        """True if the report is under legal hold."""
        if self.legal_hold_until is None:
            return False
        hold = self.legal_hold_until
        if hold.tzinfo is None:
            hold = hold.replace(tzinfo=timezone.utc)
        return hold > datetime.now(timezone.utc)

    @property
    def is_regenerated(self) -> bool:
        """True if this report was created by re-running an earlier one."""
        return self.regenerated_from_id is not None

    @property
    def is_compromised(self) -> bool:
        """True if integrity verification has failed."""
        return not self.integrity_verified

    @property
    def file_size_mb(self) -> float | None:
        """File size in megabytes, for display. None if not yet generated."""
        if self.file_size_bytes is None:
            return None
        return round(self.file_size_bytes / (1024 * 1024), 2)


