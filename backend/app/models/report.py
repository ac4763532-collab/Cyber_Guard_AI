"""
CyberGuard AI — Security Reports
============================================================================

The ``security_reports`` table: the Reporting Agent's output.

Every PDF investigation report, CSV incident export, JSON summary, and
HTML dashboard snapshot becomes a row here, with a file on disk and full
traceability back to what produced it.

Reports have a different lifecycle than other security artifacts:

    - **Asynchronous generation.** A monthly report may take seconds to
      minutes. The API returns ``queued``; a worker flips to ``ready``.
    - **Immutable artifacts.** Once ready, content is fixed. Re-running
      creates a new row with ``regenerated_from_id`` linking back. Silent
      overwrites are impossible.
    - **Multi-format.** A case investigation often needs both PDF (for
      the client) and CSV (for internal analysis). Same logical report,
      two files, grouped by ``report_group_id``.
    - **Reproducible.** Every row stores the exact ``parameters`` used.
      A compliance auditor can regenerate byte-identical reports later.

Design decisions
----------------
1. **``regenerated_from_id`` self-FK.**
   Reports form an immutable chain. Re-running creates a new row with
   ``regenerated_from_id`` pointing to the previous one. Never a silent
   overwrite.

2. **``report_group_id`` groups multi-format siblings.**
   A PDF and its CSV share a ``report_group_id``. Querying "all files for
   report X" is one WHERE clause.

3. **``scope_type`` + ``scope_id`` polymorphic reference.**
   Reports can cover workspace, organization, case, incident, analyst,
   or source.

4. **``parameters`` JSONB is the reproducibility contract.**
   Stores the exact time range, entity IDs, section filters, and format
   options. Any report can be regenerated by replaying the same
   parameters.

5. **``sections`` JSONB — section-level control.**
   A long report includes multiple sections (executive_summary,
   threat_landscape, timeline, ...). Storing the section list enables
   searching "reports that contain a threat landscape section".

6. **``content_hash`` mandatory.**
   Verifies the file on disk. Mismatch → ``integrity_verified=False``.
   Cannot create a report without a hash.

7. **Storage path is derived, not stored.**
   Files live at ``static/reports/{workspace_id}/{report_id}.{format}``.
   Computed by ``get_storage_path()`` — same pattern as evidence.

8. **``period_start_at`` + ``period_end_at``.**
   Time-range metadata. For daily reports, day boundaries. For incident
   reports, the incident's time window.

9. **``generation_duration_seconds`` as a stored column.**
   Monitoring and SLA. If reports start taking 60s instead of 3s, this
   field makes that visible.

10. **``error_code`` + ``error_message`` for failed generations.**
    Structured failure information. Retry logic reads the code, not the
    message.

11. **``shared_with`` JSONB array.**
    Reports can be shared with specific users beyond workspace members
    (e.g. analyst shares a PDF with a client). Small lists (1-3 people).

12. **``is_scheduled`` + ``schedule_id``.**
    Distinguishes manually-requested from scheduled reports.

13. **``download_count`` + ``last_downloaded_at``.**
    Usage analytics. Detects unused report types and popular ones.

14. **``expires_at``.**
    Reports auto-expire (default 90 days). Background job hard-deletes
    row and file. ``is_under_legal_hold`` overrides.

15. **``SoftDeleteMixin`` — two-phase deletion.**
    User delete → soft-delete immediately; hard-delete after retention
    window expires AND no legal hold.

16. **Timezone correctness everywhere.**

Usage
-----
    from app.models import SecurityReport
    from app.models.enums import ReportType

    # Manual report request
    report = SecurityReport.build(
        workspace_id=workspace.id,
        requested_by_id=analyst.id,
        report_type=ReportType.INCIDENT,
        report_format="pdf",
        title="Incident Report — Brute force against alice",
        scope_type="incident",
        scope_id=incident.id,
        parameters={
            "incident_id": str(incident.id),
            "include_evidence": True,
            "include_recommendations": True,
        },
        sections=["executive_summary", "timeline", "evidence", "recommendations"],
        period_start_at=incident.opened_at,
        period_end_at=incident.closed_at,
    )
    db.add(report)
    db.commit()

    # Background worker picks up QUEUED reports
    report.start_generation()
    db.commit()

    # ... generate file ...
    report.finish_generation(
        content_hash=sha256_of_file,
        file_size_bytes=os.path.getsize(path),
        page_count=14,
        summary="Investigation of sustained brute-force attack.",
    )
    db.commit()

    # Multi-format: create a second row for CSV
    csv_report = SecurityReport.build(
        ...,
        report_format="csv",
        report_group_id=report.report_group_id,
        regenerated_from_id=None,
    )
"""

