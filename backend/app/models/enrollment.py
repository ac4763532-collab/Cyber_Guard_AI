"""
CyberGuard AI — Source Enrollment Tokens
============================================================================

The ``source_enrollments`` table: short-lived, one-time-use tokens that
authorize a collector to enroll a specific security source.

This is the **handoff point** between:

    "A user wants to connect their laptop to CyberGuard"
    and
    "The collector on the laptop has a credential to send events."

It is also the only moment a **plaintext secret** (the enrollment token)
crosses from backend to collector. Everything about this table is designed
to shrink the attack surface of that single moment.

Design decisions
----------------
1. **Only the bcrypt hash is stored.** The plaintext token is:

       - generated by the backend (256 bits from ``secrets``)
       - returned to the user **once** in the API response
       - shown in the UI during the enrollment wizard
       - never stored in plaintext anywhere

   If the database leaks, no live enrollment tokens exist. bcrypt hash +
   256-bit input = brute force is infeasible.

2. **``token_prefix`` (12 chars, plaintext) for log identification.**
   Without this, every token line in the audit log looks identical
   (``enr_*******``). With it, incidents can be traced: "the token
   ``enr_a1b2c3d4`` was redeemed from 203.0.113.42". First 12 chars only —
   not enough to reconstruct the full token.

3. **At most one active enrollment token per source — DB-enforced.**
   A partial unique index ``WHERE redeemed_at IS NULL AND revoked_at IS
   NULL`` guarantees this. Without it, clicking "Generate Token" twice
   would create two live tokens — doubling the attack surface for no
   reason.

4. **Short TTL, server-computed.** Default 15 minutes (from
   ``COLLECTOR_ENROLLMENT_TOKEN_TTL_MINUTES``). ``expires_at`` is computed
   at creation time. A ``CHECK`` constraint enforces ``expires_at >
   created_at`` as defense in depth; the service layer enforces the actual
   window.

5. **Bound to a specific source AND a specific user.** A token can only
   enroll *this* source, and only when redeemed by the user who created it.
   Both bindings are checked by the redemption service.

6. **No ``SoftDeleteMixin``.** Lifecycle is encoded in three timestamps:

       expires_at     — automatic expiry (TTL)
       redeemed_at    — successful use (one-time)
       revoked_at     — explicit invalidation by an admin

   A token is redeemable iff all three timestamps are NULL (i.e. not
   expired, not used, not revoked). "Deleting" a token is nonsensical — a
   token is one of {pending, redeemed, expired, revoked}.

7. **Two-tier audit metadata.** Creation-time context:

       metadata          JSONB     — IP, user agent at creation
       created_by_id     UUID      — who requested the token

   Redemption-time context:

       redeemed_at       TIMESTAMP — when it was used
       redeemed_by_id    UUID      — which user completed enrollment
       redeemed_ip       VARCHAR   — from what IP
       redeemed_user_agent VARCHAR — from what client
       collector_version VARCHAR   — what version of the collector

   This lets a forensic investigator reconstruct the entire enrollment
   event from a single row, even years later.

8. **Timezone-correct everywhere.** All timestamps are ``TIMESTAMPTZ`` in
   UTC. Naive datetimes are rejected at ORM level.

Usage
-----
    from datetime import timedelta
    from app.models import SourceEnrollment
    from app.core.security import generate_secure_token, hash_password

    # Generate a token for a pending source
    plaintext_token = generate_secure_token(32)  # ~43 chars, URL-safe
    enrollment = SourceEnrollment.build(
        source_id=source.id,
        created_by_id=user.id,
        token_hash=hash_password(plaintext_token),
        token_prefix=plaintext_token[:12].lower(),
        ttl_minutes=15,
        metadata={"ip": "203.0.113.42", "user_agent": "Chrome/120"},
    )
    db.add(enrollment)
    db.commit()

    # IMPORTANT: return ``plaintext_token`` to the caller NOW.
    # It is never retrievable again.

    # Later, when the collector presents the token:
    if not enrollment.is_redeemable:
        raise EnrollmentTokenInvalidError(...)

    if not verify_password(presented_token, enrollment.token_hash):
        raise EnrollmentTokenInvalidError(...)

    enrollment.redeemed_at = datetime.now(timezone.utc)
    enrollment.redeemed_by_id = user.id
    enrollment.redeemed_ip = collector_ip
    enrollment.collector_version = collector_version
    db.commit()
"""

from __future__ import annotations

import re
import uuid
from datetime import datetime, timedelta, timezone
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, validates

from app.core.exceptions import ValidationError
from app.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin


#: Pattern for token_prefix: ``enr-<8 lowercase hex>`` (12 chars).
_TOKEN_PREFIX_PATTERN = re.compile(r"^enr-[a-f0-9]{8}$")

_MAX_TOKEN_PREFIX_LENGTH = 12
_MAX_IP_ADDRESS_LENGTH = 45  # IPv6 max with zone id
_MAX_USER_AGENT_LENGTH = 512
_MAX_COLLECTOR_VERSION_LENGTH = 32
_MAX_REVOCATION_REASON_LENGTH = 500


class SourceEnrollment(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    A short-lived, one-time-use enrollment token for a security source.

    A valid token authorizes exactly one collector instance to enroll
    exactly one source, within exactly one TTL window, exactly once.
    """

    __tablename__ = "source_enrollments"

    __table_args__ = (
        # Prefix format
        CheckConstraint(
            r"token_prefix ~ '^enr-[a-f0-9]{8}$'",
            name="token_prefix_format",
        ),
        # Expiry must be in the future relative to creation.
        CheckConstraint(
            "expires_at > created_at",
            name="expires_after_created",
        ),
        # Cannot be revoked without a reason or a revoked_at timestamp pair.
        CheckConstraint(
            "(revoked_at IS NULL AND revocation_reason IS NULL) OR "
            "(revoked_at IS NOT NULL)",
            name="revocation_pair",
        ),
        # At most one active enrollment token per source.
        Index(
            "uq_active_enrollment_per_source",
            "source_id",
            unique=True,
            postgresql_where=text(
                "redeemed_at IS NULL AND revoked_at IS NULL"
            ),
        ),
        # Frequent query: source's enrollment history.
        Index(
            "ix_enrollments_source_created",
            "source_id",
            "created_at",
        ),
    )

    # ────────────────────────────────────────────────────────────────────
    # Bindings
    # ────────────────────────────────────────────────────────────────────

    source_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("security_sources.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="The source this token authorizes enrollment for.",
    )

    created_by_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment="User who requested the token. SET NULL after user hard-delete.",
    )

    # ────────────────────────────────────────────────────────────────────
    # Token
    # ────────────────────────────────────────────────────────────────────

    token_hash: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        comment="bcrypt hash of the plaintext token. Never the plaintext.",
    )

    token_prefix: Mapped[str] = mapped_column(
        String(_MAX_TOKEN_PREFIX_LENGTH),
        nullable=False,
        index=True,
        comment="First 12 chars of the token, plaintext, for logs and UI.",
    )

    # ────────────────────────────────────────────────────────────────────
    # Lifecycle
    # ────────────────────────────────────────────────────────────────────

    expires_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
        comment="Server-computed TTL boundary (created_at + TTL).",
    )

    redeemed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
        comment="When the token was successfully redeemed. NULL = not yet used.",
    )

    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="When the token was explicitly invalidated by an admin or user.",
    )

    revocation_reason: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Reason recorded when the token was revoked.",
    )

    # ────────────────────────────────────────────────────────────────────
    # Creation context (audit)
    # ────────────────────────────────────────────────────────────────────

    metadata_json: Mapped[dict[str, Any]] = mapped_column(
        "metadata",
        JSONB,
        nullable=False,
        default=dict,
        server_default=text("'{}'::jsonb"),
        comment=(
            "Creation context: {ip, user_agent, ...} at the moment the token "
            "was issued. Shape validated by the service layer."
        ),
    )

    # ────────────────────────────────────────────────────────────────────
    # Redemption context (audit)
    # ────────────────────────────────────────────────────────────────────

    redeemed_by_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment="User who completed enrollment. Must match created_by_id.",
    )

    redeemed_ip: Mapped[str | None] = mapped_column(
        String(_MAX_IP_ADDRESS_LENGTH),
        nullable=True,
        comment="Source IP of the collector at redemption time.",
    )

    redeemed_user_agent: Mapped[str | None] = mapped_column(
        String(_MAX_USER_AGENT_LENGTH),
        nullable=True,
        comment="Collector client identifier at redemption time.",
    )

    collector_version: Mapped[str | None] = mapped_column(
        String(_MAX_COLLECTOR_VERSION_LENGTH),
        nullable=True,
        comment="Version string reported by the collector at enrollment.",
    )

    # ====================================================================
    # VALIDATORS
    # ====================================================================

    @validates("token_prefix")
    def _validate_token_prefix(self, _key: str, value: str) -> str:
        if not isinstance(value, str):
            raise ValidationError(
                message="token_prefix must be a string",
                code="ENROLLMENT_PREFIX_INVALID_TYPE",
            )
        stripped = value.strip().lower()
        if not _TOKEN_PREFIX_PATTERN.match(stripped):
            raise ValidationError(
                message=(
                    "token_prefix must match the format "
                    "'enr-<8 lowercase hex chars>' (e.g. 'enr-a1b2c3d4')"
                ),
                code="ENROLLMENT_PREFIX_INVALID_FORMAT",
                details={"received": stripped},
            )
        return stripped

    @validates("revocation_reason")
    def _validate_revocation_reason(
        self, _key: str, value: str | None
    ) -> str | None:
        if value is None:
            return None
        if not isinstance(value, str):
            raise ValidationError(
                message="revocation_reason must be a string or None",
                code="ENROLLMENT_REASON_INVALID_TYPE",
            )
        stripped = value.strip()
        if not stripped:
            return None
        if len(stripped) > _MAX_REVOCATION_REASON_LENGTH:
            raise ValidationError(
                message=(
                    f"revocation_reason must not exceed "
                    f"{_MAX_REVOCATION_REASON_LENGTH} characters"
                ),
                code="ENROLLMENT_REASON_TOO_LONG",
            )
        return stripped

    @validates("metadata_json")
    def _validate_metadata(
        self, _key: str, value: dict[str, Any] | None
    ) -> dict[str, Any]:
        if value is None:
            return {}
        if not isinstance(value, dict):
            raise ValidationError(
                message="metadata must be a dict",
                code="ENROLLMENT_METADATA_INVALID_TYPE",
            )
        return value

    @validates("redeemed_ip")
    def _validate_redeemed_ip(self, _key: str, value: str | None) -> str | None:
        if value is None:
            return None
        if not isinstance(value, str):
            raise ValidationError(
                message="redeemed_ip must be a string or None",
                code="ENROLLMENT_IP_INVALID_TYPE",
            )
        stripped = value.strip()
        if not stripped:
            return None
        if len(stripped) > _MAX_IP_ADDRESS_LENGTH:
            raise ValidationError(
                message=f"redeemed_ip must not exceed {_MAX_IP_ADDRESS_LENGTH} characters",
                code="ENROLLMENT_IP_TOO_LONG",
            )
        return stripped

    # ====================================================================
    # CONSTRUCTION HELPER
    # ====================================================================

    @classmethod
    def build(
        cls,
        *,
        source_id: uuid.UUID,
        created_by_id: uuid.UUID,
        token_hash: str,
        token_prefix: str,
        ttl_minutes: int = 15,
        metadata: dict[str, Any] | None = None,
    ) -> "SourceEnrollment":
        """
        Construct a new enrollment token record.

        The caller is responsible for:

            - generating the plaintext token via ``generate_secure_token``
            - hashing it via ``hash_password``
            - passing the hash and prefix
            - returning the plaintext to the caller of the endpoint
              **immediately** — it cannot be recovered from this row

        ``ttl_minutes`` must be a positive integer. The service layer should
        pass ``settings.COLLECTOR_ENROLLMENT_TOKEN_TTL_MINUTES``.
        """
        if ttl_minutes <= 0:
            raise ValidationError(
                message="ttl_minutes must be a positive integer",
                code="ENROLLMENT_TTL_INVALID",
                details={"ttl_minutes": ttl_minutes},
            )

        now = datetime.now(timezone.utc)

        return cls(
            source_id=source_id,
            created_by_id=created_by_id,
            token_hash=token_hash,
            token_prefix=token_prefix,
            expires_at=now + timedelta(minutes=ttl_minutes),
            metadata_json=metadata or {},
        )

    # ====================================================================
    # STATE PROPERTIES
    # ====================================================================

    @property
    def is_expired(self) -> bool:
        """True if the TTL window has passed."""
        exp = self.expires_at
        if exp.tzinfo is None:
            exp = exp.replace(tzinfo=timezone.utc)
        return exp <= datetime.now(timezone.utc)

    @property
    def is_redeemed(self) -> bool:
        """True if the token has already been used."""
        return self.redeemed_at is not None

    @property
    def is_revoked(self) -> bool:
        """True if the token was explicitly invalidated."""
        return self.revoked_at is not None

    @property
    def is_redeemable(self) -> bool:
        """
        The single gate every redemption check must consult.

        True iff:
          - not yet redeemed
          - not revoked
          - not expired

        If this returns False, redemption must be refused — regardless of
        whether the presented plaintext matches the stored hash.
        """
        return (
            not self.is_redeemed
            and not self.is_revoked
            and not self.is_expired
        )

    @property
    def display_status(self) -> str:
        """
        Human-readable identifier for the UI. One of:

            pending    — still redeemable
            redeemed   — already used
            expired    — TTL passed without redemption
            revoked    — explicitly invalidated

        Stable string identifiers for i18n on the frontend.
        """
        if self.is_redeemed:
            return "redeemed"
        if self.is_revoked:
            return "revoked"
        if self.is_expired:
            return "expired"
        return "pending"

    @property
    def seconds_until_expiry(self) -> int:
        """
        Seconds remaining before expiry. Negative if already expired.
        Useful for the UI countdown during the enrollment wizard.
        """
        exp = self.expires_at
        if exp.tzinfo is None:
            exp = exp.replace(tzinfo=timezone.utc)
        delta = (exp - datetime.now(timezone.utc)).total_seconds()
        return int(delta)


