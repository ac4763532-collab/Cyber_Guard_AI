"""
CyberGuard AI — Security Sources and Credentials
============================================================================

Two tables:

    security_sources    — every registered device, log source, network tap,
                          email account, or database sending events.
    source_credentials  — per-source collector credentials for authenticated
                          event ingestion.

This file is the schema manifestation of the interaction document's rule
"Don't confuse connection with monitoring". The source table carries **five
separate connection indicators** so the UI can render each independently:

    collector_connected         Is the collector process running?
    last_heartbeat_at           When did the collector last check in?
    collection_active           Has the user enabled event collection?
    last_event_at               When did we last receive a real event?
    agent_processing_healthy    Are agents processing events without errors?

A connected source is not the same as a monitored source. A monitored
source is not the same as a healthy source. Collapsing these into one
boolean would make the UI lie. This schema refuses to.

Design decisions
----------------
1. **``source_key`` is a human-readable short ID.** UUIDs are fine
   internally, but analysts need "the laptop on Floor 3" to have a stable
   identifier in audit logs and reports. Format: ``src-<8 hex chars>``.
   Unique within workspace.

2. **Credentials are separate from the source.** Rotation is
   per-credential, not per-source. During a rotation window, a source may
   have **two** active credentials — the old one (still accepted) and the
   new one (already issued). The credential table supports this naturally.

3. **Only the hash of the credential is stored.** The collector receives
   the plaintext **once** at enrollment. The backend stores the bcrypt hash
   and a short plaintext **prefix** (first 12 chars) for identification in
   logs. If the DB leaks, no live collector tokens are compromised.

4. **``credential_prefix``** — 12 chars of the credential, plaintext, for
   log identification. Without it, every credential line in a log looks
   identical (`cgc_*****`) and incident investigations become impossible.

5. **``ON DELETE CASCADE`` on ``workspace_id``; ``RESTRICT`` on
   ``registered_by_id``.** A deleted workspace's sources are meaningless
   and cascade. But a deleted user's *registered* sources stay — the audit
   log preserves attribution. `registered_by_id` is `SET NULL` to reflect
   that the registering user is gone while the source remains.

6. **No ``SoftDeleteMixin`` on sources.** The ``status`` field
   (`active`, `disabled`, `revoked`, `disconnected`, `error`) encodes
   lifecycle. A source can be in ``error`` state indefinitely while still
   needing to be queried. Soft delete would add a second state axis and
   obscure the first.

7. **``config`` and ``capabilities`` are JSONB.** Collector-specific
   configuration (Windows channel list, Linux log file paths, network
   interface) varies wildly across source types. Shape validated by
   Pydantic schemas per source type, not by DB.

8. **Denormalized counters.** ``events_ingested_count`` and
   ``events_failed_count`` are maintained by the ingestion service. They
   drive UI health indicators and are checked by the collector health
   monitor. Computing ``COUNT(*)`` per source on every page load would be
   too slow.

9. **5 connection indicators, each with its own meaning.** See the docstring
   of the ``security_sources`` table class for the precise semantics of each.

Usage
-----
    from app.models import SecuritySource, SourceCredential
    from app.models.enums import SourceType, SourceStatus

    # A user registers their Windows laptop
    source = SecuritySource(
        workspace_id=workspace.id,
        registered_by_id=user.id,
        name="Priya's Laptop",
        source_type=SourceType.WINDOWS,
        status=SourceStatus.PENDING_ENROLLMENT,
        source_key="src-a1b2c3d4",  # generated by service
    )
    db.add(source)
    db.commit()

    # A collector enrolls
    source.status = SourceStatus.ACTIVE
    source.collector_connected = True
    source.collection_active = True

    # The backend issues a credential (plaintext returned to collector once,
    # hash stored here)
    cred = SourceCredential(
        source_id=source.id,
        credential_prefix="cgc_a1b2c3",       # first 12 chars
        secret_hash=hash_password(plaintext), # bcrypt hash
        description="Windows Collector v1.0",
    )
    db.add(cred)
    db.commit()
"""

from __future__ import annotations

import re
import uuid
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, validates

from app.core.exceptions import ValidationError
from app.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin
from app.models.enums import (
    CredentialStatus,
    SourceStatus,
    SourceType,
    enum_column_type,
)


#: Pattern for source_key: ``src-<8 hex chars>``.
#: Enforced at ORM level; the service generates compliant keys.
_SOURCE_KEY_PATTERN = re.compile(r"^src-[a-f0-9]{8}$")

#: Pattern for credential_prefix: ``cgc_<8 hex chars>`` (13 chars total).
_CREDENTIAL_PREFIX_PATTERN = re.compile(r"^cgc_[a-f0-9]{8}$")

_MAX_NAME_LENGTH = 120
_MAX_DESCRIPTION_LENGTH = 2000
_MAX_HOSTNAME_LENGTH = 255
_MAX_IP_ADDRESS_LENGTH = 45  # max IPv6 with zone id
_MAX_OS_VERSION_LENGTH = 64
_MAX_AGENT_VERSION_LENGTH = 32
_MAX_CAPABILITIES = 20
_MAX_CONFIG_SIZE_BYTES = 32 * 1024  # 32 KB cap on JSONB config


# ============================================================================
# SECURITY SOURCE
# ============================================================================

class SecuritySource(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    A registered security source: a device, log stream, network tap, email
    account, or database whose events the platform monitors.

    The five connection indicators
    ------------------------------
    1. **collector_connected** (bool)
       The collector process is currently running and has an open session
       with the backend. Set by the heartbeat service: True when a
       heartbeat arrives, False when the collector calls disconnect or when
       it exceeds ``COLLECTOR_STALE_AFTER_SECONDS``.

    2. **last_heartbeat_at** (timestamp)
       The timestamp of the most recent heartbeat from the collector.
       Updated on every heartbeat regardless of other fields.

    3. **collection_active** (bool)
       User-controlled switch: "should this source be collecting events
       right now?". A source can be connected but have collection disabled
       (e.g. during maintenance windows or when the user wants to pause
       monitoring without revoking credentials).

    4. **last_event_at** (timestamp)
       The timestamp of the most recent event actually ingested from this
       source. This is the only field that proves end-to-end data flow.
       A source can be collector_connected=True, collection_active=True,
       and still have a stale last_event_at — that indicates a broken pipe
       or a source with nothing to report.

    5. **agent_processing_healthy** (bool)
       Whether agents have been successfully processing events from this
       source recently. Set to False by the agent runtime when it detects
       consecutive processing failures. Independent of connection status —
       events can arrive but fail to analyze.
    """

    __tablename__ = "security_sources"

    __table_args__ = (
        # source_key format
        CheckConstraint(
            r"source_key ~ '^src-[a-f0-9]{8}$'",
            name="source_key_format",
        ),
        # Source key unique within workspace — partial index below.
        # Counters must be non-negative.
        CheckConstraint(
            "events_ingested_count >= 0",
            name="events_ingested_count_non_negative",
        ),
        CheckConstraint(
            "events_failed_count >= 0",
            name="events_failed_count_non_negative",
        ),
        # Heartbeat must be at or before current time (sanity).
        # Enforced at service layer; CHECK for extreme cases only.
        CheckConstraint(
            "last_heartbeat_at IS NULL OR last_heartbeat_at <= now() + interval '1 hour'",
            name="heartbeat_not_in_future",
        ),
        CheckConstraint(
            "last_event_at IS NULL OR last_event_at <= now() + interval '1 hour'",
            name="last_event_not_in_future",
        ),
        # Unique source_key within workspace.
        Index(
            "uq_source_key_per_workspace",
            "workspace_id",
            "source_key",
            unique=True,
        ),
        # Frequent query: active sources in workspace.
        Index(
            "ix_sources_workspace_status",
            "workspace_id",
            "status",
        ),
        # Frequent query: sources by type (for agent routing).
        Index(
            "ix_sources_type_status",
            "source_type",
            "status",
        ),
    )

    # ────────────────────────────────────────────────────────────────────
    # Identity & scope
    # ────────────────────────────────────────────────────────────────────

    workspace_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Owning workspace. Deleting the workspace cascades sources.",
    )

    registered_by_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment=(
            "User who registered this source. SET NULL on user hard-delete — "
            "the audit log retains attribution."
        ),
    )

    source_key: Mapped[str] = mapped_column(
        String(13),
        nullable=False,
        index=True,
        comment="Stable short identifier (e.g. 'src-a1b2c3d4'). Unique per workspace.",
    )

    name: Mapped[str] = mapped_column(
        String(_MAX_NAME_LENGTH),
        nullable=False,
        comment="Human-readable name shown in UI and reports.",
    )

    description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Free-text description of what this source monitors.",
    )

    # ────────────────────────────────────────────────────────────────────
    # Type and status
    # ────────────────────────────────────────────────────────────────────

    source_type: Mapped[SourceType] = mapped_column(
        enum_column_type(SourceType),
        nullable=False,
        index=True,
        comment="Category of source (windows, linux, email, network, ...).",
    )

    status: Mapped[SourceStatus] = mapped_column(
        enum_column_type(SourceStatus),
        nullable=False,
        default=SourceStatus.PENDING_ENROLLMENT,
        server_default=SourceStatus.PENDING_ENROLLMENT.value,
        index=True,
        comment=(
            "Lifecycle state (pending_enrollment, active, disabled, "
            "revoked, disconnected, error)."
        ),
    )

    # ────────────────────────────────────────────────────────────────────
    # Connection indicators (the 5 — see class docstring)
    # ────────────────────────────────────────────────────────────────────

    collector_connected: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        server_default="false",
        comment="Set True when a heartbeat arrives; False on disconnect or staleness.",
    )

    last_heartbeat_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
        comment="Timestamp of the most recent collector heartbeat.",
    )

    collection_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        server_default="false",
        comment="User-controlled switch: is this source collecting events?",
    )

    last_event_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
        comment="Timestamp of the most recent event ingested from this source.",
    )

    agent_processing_healthy: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
        server_default="true",
        comment="False when agents have recently failed to process this source's events.",
    )

    # ────────────────────────────────────────────────────────────────────
    # Collector identity (populated at enrollment, informational)
    # ────────────────────────────────────────────────────────────────────

    hostname: Mapped[str | None] = mapped_column(
        String(_MAX_HOSTNAME_LENGTH),
        nullable=True,
        comment="Hostname reported by the collector at enrollment.",
    )

    ip_address: Mapped[str | None] = mapped_column(
        String(_MAX_IP_ADDRESS_LENGTH),
        nullable=True,
        comment="Last-seen IP address of the collector. Updated on heartbeat.",
    )

    os_version: Mapped[str | None] = mapped_column(
        String(_MAX_OS_VERSION_LENGTH),
        nullable=True,
        comment="OS version reported by the collector at enrollment.",
    )

    agent_version: Mapped[str | None] = mapped_column(
        String(_MAX_AGENT_VERSION_LENGTH),
        nullable=True,
        comment="Collector agent version reported at enrollment.",
    )

    # ────────────────────────────────────────────────────────────────────
    # Configuration and capabilities (JSONB)
    # ────────────────────────────────────────────────────────────────────

    config: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
        server_default=text("'{}'::jsonb"),
        comment=(
            "Collector configuration (channels, log paths, interface, ...). "
            "Shape validated by Pydantic per source_type."
        ),
    )

    capabilities: Mapped[list[str]] = mapped_column(
        JSONB,
        nullable=False,
        default=list,
        server_default=text("'[]'::jsonb"),
        comment=(
            "What this source can provide (log_collection, network_monitoring, "
            "email_scan, database_audit, ...). Gates which agents apply."
        ),
    )

    # ────────────────────────────────────────────────────────────────────
    # Counters (denormalized, maintained by ingestion service)
    # ────────────────────────────────────────────────────────────────────

    events_ingested_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
        comment="Lifetime events successfully ingested from this source.",
    )

    events_failed_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
        comment="Lifetime events rejected from this source (validation, dup, ...).",
    )

    # ====================================================================
    # VALIDATORS
    # ====================================================================

    @validates("source_key")
    def _validate_source_key(self, _key: str, value: str) -> str:
        if not isinstance(value, str):
            raise ValidationError(
                message="source_key must be a string",
                code="SOURCE_KEY_INVALID_TYPE",
            )
        stripped = value.strip().lower()
        if not _SOURCE_KEY_PATTERN.match(stripped):
            raise ValidationError(
                message=(
                    "source_key must match the format 'src-<8 lowercase "
                    "hex chars>' (e.g. 'src-a1b2c3d4')"
                ),
                code="SOURCE_KEY_INVALID_FORMAT",
                details={"received": stripped},
            )
        return stripped

    @validates("name")
    def _validate_name(self, _key: str, value: str) -> str:
        if not isinstance(value, str):
            raise ValidationError(
                message="name must be a string",
                code="SOURCE_NAME_INVALID_TYPE",
            )
        stripped = value.strip()
        if not stripped:
            raise ValidationError(
                message="name must not be empty",
                code="SOURCE_NAME_EMPTY",
            )
        if len(stripped) > _MAX_NAME_LENGTH:
            raise ValidationError(
                message=f"name must not exceed {_MAX_NAME_LENGTH} characters",
                code="SOURCE_NAME_TOO_LONG",
            )
        return stripped

    @validates("description")
    def _validate_description(self, _key: str, value: str | None) -> str | None:
        if value is None:
            return None
        if not isinstance(value, str):
            raise ValidationError(
                message="description must be a string or None",
                code="SOURCE_DESCRIPTION_INVALID_TYPE",
            )
        stripped = value.strip()
        if not stripped:
            return None
        if len(stripped) > _MAX_DESCRIPTION_LENGTH:
            raise ValidationError(
                message=f"description must not exceed {_MAX_DESCRIPTION_LENGTH} characters",
                code="SOURCE_DESCRIPTION_TOO_LONG",
            )
        return stripped

    @validates("source_type")
    def _validate_source_type(
        self, _key: str, value: SourceType | str
    ) -> SourceType:
        if isinstance(value, SourceType):
            return value
        if isinstance(value, str):
            try:
                return SourceType(value)
            except ValueError as exc:
                raise ValidationError(
                    message=f"Invalid source_type {value!r}",
                    code="SOURCE_TYPE_INVALID",
                    details={"allowed": list(SourceType.values())},
                ) from exc
        raise ValidationError(
            message="source_type must be a SourceType or string",
            code="SOURCE_TYPE_INVALID_TYPE",
        )

    @validates("status")
    def _validate_status(self, _key: str, value: SourceStatus | str) -> SourceStatus:
        if isinstance(value, SourceStatus):
            return value
        if isinstance(value, str):
            try:
                return SourceStatus(value)
            except ValueError as exc:
                raise ValidationError(
                    message=f"Invalid status {value!r}",
                    code="SOURCE_STATUS_INVALID",
                    details={"allowed": list(SourceStatus.values())},
                ) from exc
        raise ValidationError(
            message="status must be a SourceStatus or string",
            code="SOURCE_STATUS_INVALID_TYPE",
        )

    @validates("capabilities")
    def _validate_capabilities(
        self, _key: str, value: list[str] | None
    ) -> list[str]:
        if value is None:
            return []
        if not isinstance(value, list):
            raise ValidationError(
                message="capabilities must be a list of strings",
                code="SOURCE_CAPABILITIES_INVALID_TYPE",
            )
        if len(value) > _MAX_CAPABILITIES:
            raise ValidationError(
                message=f"capabilities must not exceed {_MAX_CAPABILITIES} items",
                code="SOURCE_CAPABILITIES_TOO_MANY",
            )
        cleaned: list[str] = []
        seen: set[str] = set()
        for item in value:
            if not isinstance(item, str):
                raise ValidationError(
                    message="each capability must be a string",
                    code="SOURCE_CAPABILITY_INVALID_TYPE",
                )
            stripped = item.strip().lower()
            if not stripped or stripped in seen:
                continue
            seen.add(stripped)
            cleaned.append(stripped)
        return cleaned

    # ====================================================================
    # STATE PROPERTIES
    # ====================================================================

    @property
    def is_active(self) -> bool:
        """True if the source's status is ACTIVE."""
        return self.status == SourceStatus.ACTIVE

    @property
    def is_disabled(self) -> bool:
        """True if the source has been disabled by a user."""
        return self.status == SourceStatus.DISABLED

    @property
    def is_revoked(self) -> bool:
        """True if the source's credentials have been revoked."""
        return self.status == SourceStatus.REVOKED

    @property
    def is_healthy(self) -> bool:
        """
        Composite health check used by dashboards.

        A source is healthy iff:
          - status is ACTIVE
          - collector is connected
          - collection is active
          - agents are processing without errors
          - an event has been received in the last 24 hours
            (via ``received_event_recently``)

        This is a *summary* property — the five indicators remain the
        source of truth. Use this only for aggregate dashboards.
        """
        return (
            self.status == SourceStatus.ACTIVE
            and self.collector_connected
            and self.collection_active
            and self.agent_processing_healthy
        )

    @property
    def received_event_recently(self, hours: int = 24) -> bool:
        """
        True if an event has been received in the last ``hours`` hours.

        Note: implemented as a **property** with an optional parameter, so
        callers can use ``source.received_event_recently`` for the default
        24-hour window or ``source.received_event_recently.__wrapped__`` if
        they need a custom window. For custom windows, use the helper
        method ``has_received_event_since(dt)`` below instead.
        """
        from datetime import timedelta

        if self.last_event_at is None:
            return False
        threshold = datetime.now(timezone.utc) - timedelta(hours=hours)
        last = self.last_event_at
        if last.tzinfo is None:
            last = last.replace(tzinfo=timezone.utc)
        return last > threshold

    def has_received_event_since(self, since: datetime) -> bool:
        """Return True if ``last_event_at`` is after ``since`` (both UTC)."""
        if self.last_event_at is None:
            return False
        last = self.last_event_at
        if last.tzinfo is None:
            last = last.replace(tzinfo=timezone.utc)
        if since.tzinfo is None:
            since = since.replace(tzinfo=timezone.utc)
        return last > since

    @property
    def display_status(self) -> str:
        """
        Human-readable status for the UI, combining the 5 indicators into
        the 7 states defined in the interaction document:

            Not connected | Enrollment pending | Connected | No recent
            events | Disconnected | Disabled | Revoked

        The exact string values here are meant to be replaced by i18n
        labels in the frontend — this is a stable enum-like identifier.
        """
        if self.status == SourceStatus.PENDING_ENROLLMENT:
            return "enrollment_pending"
        if self.status == SourceStatus.DISABLED:
            return "disabled"
        if self.status == SourceStatus.REVOKED:
            return "revoked"
        if self.status == SourceStatus.ERROR:
            return "error"
        if not self.collector_connected:
            return "disconnected"
        if not self.collection_active:
            return "connected_not_collecting"
        if not self.received_event_recently:
            return "connected_no_recent_events"
        if not self.agent_processing_healthy:
            return "processing_degraded"
        return "connected"


# ============================================================================
# SOURCE CREDENTIAL
# ============================================================================

class SourceCredential(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    A collector credential for a specific source.

    Collectors authenticate each event-ingestion request with their
    credential. The plaintext is given to the collector **once** at
    enrollment. The backend stores only:

        - ``secret_hash``     (bcrypt hash — never reversible)
        - ``credential_prefix`` (first 12 chars, plaintext, for log ID)

    Rotation: a source may have **multiple active credentials** during a
    rotation window. The old one remains valid until the new one is
    confirmed working, at which point it is set to ``ROTATED``.
    """

    __tablename__ = "source_credentials"

    __table_args__ = (
        CheckConstraint(
            r"credential_prefix ~ '^cgc_[a-f0-9]{8}$'",
            name="credential_prefix_format",
        ),
        # A source may have at most N active credentials (rotation window).
        # No DB-level limit; enforced by the service layer (typically max 2).
        Index(
            "ix_source_credentials_source_status",
            "source_id",
            "status",
        ),
    )

    source_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("security_sources.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Owning source. Deleting the source cascades credentials.",
    )

    credential_prefix: Mapped[str] = mapped_column(
        String(12),
        nullable=False,
        index=True,
        comment="First 12 chars of the credential, plaintext, for log identification.",
    )

    secret_hash: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        comment="bcrypt hash of the full credential. Never the plaintext.",
    )

    status: Mapped[CredentialStatus] = mapped_column(
        enum_column_type(CredentialStatus),
        nullable=False,
        default=CredentialStatus.ACTIVE,
        server_default=CredentialStatus.ACTIVE.value,
        index=True,
        comment="Lifecycle: active, rotated, revoked, expired.",
    )

    description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Human note (e.g. 'Windows Collector v1.0, rotated 2026-02-15').",
    )

    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment=(
            "Optional expiry. Rotation cadence is enforced by the service, "
            "not by this timestamp; the field allows short-lived demo keys."
        ),
    )

    last_used_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
        comment="Updated on every successful authentication. Enables stale-key detection.",
    )

    rotated_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="When this credential was replaced by a new one.",
    )

    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="When this credential was explicitly revoked.",
    )

    revocation_reason: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Reason recorded when the credential was revoked.",
    )

    # ====================================================================
    # VALIDATORS
    # ====================================================================

    @validates("credential_prefix")
    def _validate_prefix(self, _key: str, value: str) -> str:
        if not isinstance(value, str):
            raise ValidationError(
                message="credential_prefix must be a string",
                code="CREDENTIAL_PREFIX_INVALID_TYPE",
            )
        stripped = value.strip().lower()
        if not _CREDENTIAL_PREFIX_PATTERN.match(stripped):
            raise ValidationError(
                message=(
                    "credential_prefix must match the format "
                    "'cgc-<8 lowercase hex chars>' (e.g. 'cgc-a1b2c3d4')"
                ),
                code="CREDENTIAL_PREFIX_INVALID_FORMAT",
                details={"received": stripped},
            )
        return stripped

    @validates("status")
    def _validate_status(
        self, _key: str, value: CredentialStatus | str
    ) -> CredentialStatus:
        if isinstance(value, CredentialStatus):
            return value
        if isinstance(value, str):
            try:
                return CredentialStatus(value)
            except ValueError as exc:
                raise ValidationError(
                    message=f"Invalid credential status {value!r}",
                    code="CREDENTIAL_STATUS_INVALID",
                    details={"allowed": list(CredentialStatus.values())},
                ) from exc
        raise ValidationError(
            message="status must be a CredentialStatus or string",
            code="CREDENTIAL_STATUS_INVALID_TYPE",
        )

    # ====================================================================
    # STATE PROPERTIES
    # ====================================================================

    @property
    def is_active(self) -> bool:
        """True if the credential is currently usable for authentication."""
        if self.status != CredentialStatus.ACTIVE:
            return False
        if self.expires_at is not None:
            exp = self.expires_at
            if exp.tzinfo is None:
                exp = exp.replace(tzinfo=timezone.utc)
            if exp <= datetime.now(timezone.utc):
                return False
        return True

    @property
    def is_revoked(self) -> bool:
        return self.status == CredentialStatus.REVOKED

    @property
    def is_rotated(self) -> bool:
        return self.status == CredentialStatus.ROTATED

    @property
    def is_expired(self) -> bool:
        if self.expires_at is None:
            return False
        exp = self.expires_at
        if exp.tzinfo is None:
            exp = exp.replace(tzinfo=timezone.utc)
        return exp <= datetime.now(timezone.utc)


